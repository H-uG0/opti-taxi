/**
 * Development history: simulates the working days before today as if V had
 * planned them with the tool, so that /tableau-de-bord has weeks to show.
 * For each day: trips generated from the recurrences, « Optimiser demain »
 * the evening before (real optimizer, real savePlan), sharing answers, a
 * re-optimization after each round with a refusal, the trips no plan could
 * place handed over to a partner company, validation, then the statuses the
 * crews tap on the roadmap (pickups, drop-offs, absences, cancellations).
 *
 * Run with `pnpm db:history [--days N] [--budget S]` (tsx prisma/history.ts);
 * the optimizer must be running (OPTIMIZER_URL, default http://localhost:8100).
 * Development only, with the seed's guard (prisma/safety.ts: a database on
 * this machine holding only the seed's accounts). It never touches today or
 * later dates, passes over the dates holding rows it did not create (the
 * seed's days, a day planned in the app) or changes recorded by the app (a
 * sharing answer corrected in « Courses »…) and goes further back instead, and
 * a re-run replaces only what it created (ids prefixed with "hist-", audit
 * events included), date by date: when it stops on a failure, the failing
 * date is removed, the dates before are simulated and the dates after keep
 * their previous simulation. Deterministic: every random decision comes from a
 * fixed seed (the optimizer's plans may still differ slightly between runs).
 * Like the seed, it owns its Prisma client and imports nothing server-only.
 */
import { PrismaClient } from "@prisma/client";
import { DEFAULT_LATE_CANCELLATION_HOURS } from "@/lib/domain/cancellation";
import {
  GENERATION_INCLUDE,
  planTripsFromRecurrences,
  recurrencesInRange,
  type RecurrenceForGeneration,
} from "@/lib/domain/trip-generation";
import { computeKpisByDay, summarizePeriod } from "@/lib/kpis";
import { loadKpiRows } from "@/lib/kpis-load";
import { logError } from "@/lib/log";
import { addDays, formatShortDate, todayIso } from "@/lib/time";
import { pickSimulationDates } from "./history/calendar";
import {
  clearSimulatedDay,
  foreignDates,
  foreignRows,
  simulateDay,
  type ClearedRows,
  type DayContext,
  type RowCounts,
} from "./history/day";
import { HistoryError } from "./history/errors";
import { periodSummaryLines } from "./history/kpis";
import { createOptimizerClient, optimizerBaseUrl } from "./history/optimizer";
import { HISTORY_USAGE, parseHistoryArgs } from "./history/options";
import {
  dayLabel,
  dayTableHeader,
  emptyDayReport,
  foreignRowsReason,
  formatDayLine,
  interruptedMessage,
  totalReport,
  type DayReport,
} from "./history/report";
import { assertSeedOnlyDatabase, UnsafeDatabaseError } from "./safety";

/**
 * Fixed seed of the planning instants and the crews' delays (cancellations,
 * absences and sharing answers are drawn from stable keys). With ~500 outbound
 * trips the late-arrival share of one draw varies from about 1.5 to 4.5 %
 * around a median of 3 % (replay of the stored plans of the seeded days over
 * 40 seeds); this seed is kept from the first calibration, not chosen for
 * its draw. The optimizer's plans differ slightly from run to run, so the
 * share of a real run moves within that range too.
 */
const RANDOM_SEED = 20_261_106;
/** How far back working days are looked for. */
const LOOKBACK_DAYS = 120;

const prisma = new PrismaClient();

/** Recurrences that may produce trips between `from` and `to` (same query as generateTrips). */
function loadRecurrences(from: string, to: string): Promise<RecurrenceForGeneration[]> {
  return prisma.recurrence.findMany({ where: recurrencesInRange(from, to), include: GENERATION_INCLUDE });
}

function plural(count: number, singular: string, pluralForm = `${singular}s`): string {
  return `${count} ${count > 1 ? pluralForm : singular}`;
}

function describeRows(rows: RowCounts): string {
  return `${plural(rows.trips, "course")}, ${plural(rows.routes, "tournée")}, ${plural(rows.runs, "optimisation")}`;
}

/**
 * Replaces the simulation of one date: a date holding rows the simulation did
 * not create (planned in the app, generated by the seed…) or a change the app
 * recorded on it (its audit events, reads excepted) is left as it is;
 * otherwise its previous simulation is deleted and the date simulated again,
 * right away, so a failure never leaves the following dates emptied. When
 * the simulation of the date fails, what it wrote is removed before stopping.
 */
async function replaceDay(ctx: DayContext, date: string, removed: ClearedRows, simulatedBefore: number): Promise<DayReport> {
  const { prisma } = ctx;
  const foreign = await foreignRows(prisma, date);
  if (foreign.trips + foreign.routes + foreign.runs + foreign.events > 0) {
    return emptyDayReport(date, foreignRowsReason(foreign));
  }
  const cleared = await clearSimulatedDay(prisma, date);
  removed.trips += cleared.trips;
  removed.routes += cleared.routes;
  removed.runs += cleared.runs;
  removed.events += cleared.events;
  try {
    return await simulateDay(ctx, date);
  } catch (error) {
    // Logged without the Prisma query arguments (addresses, notes), as on the server.
    if (!(error instanceof HistoryError)) logError("[history] la simulation du jour a échoué", error, { date });
    const dayRemoved = await clearSimulatedDay(prisma, date).then(
      () => true,
      () => false,
    );
    const cause = error instanceof HistoryError ? error.message : "Erreur inattendue (détail ci-dessus).";
    throw new HistoryError(interruptedMessage(date, cause, simulatedBefore, dayRemoved));
  }
}

async function main(): Promise<void> {
  const options = parseHistoryArgs(process.argv.slice(2));
  if (options.help) {
    console.log(HISTORY_USAGE);
    return;
  }
  const target = await assertSeedOnlyDatabase("history", (where) => prisma.user.count({ where }));
  const started = Date.now();
  const today = todayIso();
  console.log(`Historique simulé Opti-Taxi (données fictives) — aujourd'hui ${formatShortDate(today)}, jamais modifié`);
  console.log(`Base cible : ${target}`);

  const optimizer = createOptimizerClient(optimizerBaseUrl());
  const { matrixSource } = await optimizer.health();
  console.log(
    `Optimiseur : ${optimizer.baseUrl} (${matrixSource === "osrm" ? "distances OSRM" : "distances estimées à vol d'oiseau"}), ` +
      `temps de calcul : ${options.budgetSec === null ? "celui des paramètres" : `${options.budgetSec} s`} par optimisation`,
  );

  const lookbackFrom = addDays(today, -LOOKBACK_DAYS);
  const recurrences = await loadRecurrences(lookbackFrom, addDays(today, -1));
  const { dates, leftAlone } = pickSimulationDates(today, options.days, {
    hasTrips: (date) => planTripsFromRecurrences(recurrences, date, date).length > 0,
    foreignDates: await foreignDates(prisma, lookbackFrom, addDays(today, -1)),
    maxLookbackDays: LOOKBACK_DAYS,
  });
  const first = dates[0];
  const last = dates.at(-1);
  if (!first || !last) {
    throw new HistoryError("Aucun jour à simuler : aucune récurrence active ne produit de course avant aujourd'hui. Lancez d'abord pnpm db:seed.");
  }
  console.log(`Période : ${plural(dates.length, "jour ouvré", "jours ouvrés")}, du ${formatShortDate(first)} au ${formatShortDate(last)}`);
  if (leftAlone.length > 0) {
    console.log(`Laissés tels quels (données non créées par la simulation) : ${leftAlone.map(dayLabel).join(", ")}`);
  }

  // Who acts in the simulated days: the regulator (runs, sharing answers, validation) and the crews' accounts (statuses).
  const regulator = await prisma.user.findFirst({
    where: { role: "REGULATOR", active: true },
    orderBy: { createdAt: "asc" },
    select: { id: true },
  });
  if (!regulator) throw new HistoryError("Aucun compte régulateur actif : lancez d'abord pnpm db:seed.");
  const driverAccounts = await prisma.user.findMany({ where: { driverId: { not: null } }, select: { id: true, driverId: true } });
  const settings = await prisma.appSettings.findUnique({ where: { id: 1 }, select: { lateCancellationHours: true } });

  console.log(
    "• Simulation jour par jour, chaque jour remplaçant sa simulation précédente " +
      "(la veille : optimisation, appels, courses confiées, validation ; le jour J : statuts des équipages)",
  );
  console.log(`  ${dayTableHeader()}`);
  const ctx: DayContext = {
    prisma,
    seed: RANDOM_SEED,
    recurrences,
    optimizer,
    budgetSec: options.budgetSec,
    regulatorId: regulator.id,
    driverAccounts: new Map(driverAccounts.flatMap((user) => (user.driverId ? [[user.driverId, user.id] as const] : []))),
    lateCancellationHours: settings?.lateCancellationHours ?? DEFAULT_LATE_CANCELLATION_HOURS,
  };
  const reports: DayReport[] = [];
  const removed: ClearedRows = { trips: 0, routes: 0, runs: 0, events: 0 };
  for (const date of dates) {
    const report = await replaceDay(ctx, date, removed, reports.filter((r) => !r.skipped).length);
    reports.push(report);
    console.log(`  ${formatDayLine(report)}`);
  }

  const total = totalReport(reports);
  const simulated = reports.filter((r) => !r.skipped).length;
  console.log(
    `  Total : ${plural(simulated, "jour simulé", "jours simulés")}, ${plural(total.trips, "course")}, ` +
      `${plural(total.runs, "optimisation")}, ${total.accepted} partages acceptés et ${total.refused} refusés, ` +
      `${plural(total.handedOver, "course confiée", "courses confiées")} à un confrère (non placées par l'optimisation), ` +
      `${plural(total.refreshed, "tournée recalculée", "tournées recalculées")} après annulation` +
      (total.notRefreshed > 0 ? ` et ${plural(total.notRefreshed, "non recalculée", "non recalculées")}` : "") +
      (total.unassigned > 0 ? `, ${plural(total.unassigned, "course restée", "courses restées")} sans tournée` : ""),
  );
  console.log(
    `  Simulation précédente remplacée : ${describeRows(removed)}, ${plural(removed.events, "événement d'audit", "événements d'audit")} supprimés`,
  );

  const days = computeKpisByDay(first, last, await loadKpiRows(prisma, first, last), today);
  console.log("\nIndicateurs du tableau de bord sur la période (calcul de @/lib/kpis, comme /tableau-de-bord) :");
  for (const line of periodSummaryLines(summarizePeriod(days))) console.log(`  ${line}`);

  console.log(
    `\nSimulation terminée en ${((Date.now() - started) / 1000).toFixed(1)} s. ` +
      `Tableau de bord de la période : /tableau-de-bord?from=${first}&to=${last}`,
  );
}

main()
  .then(() => prisma.$disconnect())
  .catch(async (error: unknown) => {
    if (error instanceof HistoryError || error instanceof UnsafeDatabaseError) console.error(`\n${error.message}`);
    else logError("[history] la simulation a échoué", error);
    await prisma.$disconnect();
    process.exit(1);
  });
